#!/usr/bin/env node
// Packs manasim.js results into lab/mana-data.js for the Lab page.
// Usage: node build-lab-data.js <results-sweep-avg.json> <results-split-avg.json> <results-sweep-budget.json> > ../../../lab/mana-data.js
'use strict';
const fs = require('fs');
const [avgFile, splitFile, budgetFile] = process.argv.slice(2);
const SCN = ['P1', 'P2', 'P3', 'P4', 'P5', 'P6', 'P7', 'P8'];
const r1 = v => Math.round(v * 10);

// Main sweep: every (lands, ramp) from 35 to 55 sources, ramp split half dorks / half rocks.
const A = JSON.parse(fs.readFileSync(avgFile, 'utf8'));
const avgs = A.budgets;
const cfg = new Map();
for (const r of A.results) if (r.cell) {
  const k = r.lands + ':' + (r.dorks + r.rocks);
  if (!cfg.has(k)) cfg.set(k, { lands: r.lands, ramp: r.dorks + r.rocks, cells: {} });
  cfg.get(k).cells[r.budget] = r.cell;
}
const configs = [...cfg.values()].filter(c => avgs.every(a => c.cells[a]));
configs.sort((a, b) => a.lands - b.lands || a.ramp - b.ramp);
// per config x avg x scenario: useful T10, useful T8, unused T10, spells left in hand T10 (x10)
const v = [], cmd = [];
for (const c of configs) for (const a of avgs) {
  cmd.push(Math.round(100 * c.cells[a].P1.cmdT4));
  for (const s of SCN) { const m = c.cells[a][s]; v.push(r1(m.useful), r1(m.useful8), r1(m.unused), r1(m.left)); }
}

// Dork / rock split zoom (20,000 games per cell)
const S = JSON.parse(fs.readFileSync(splitFile, 'utf8'));
const split = S.results.filter(r => r.cell).map(r => ({ l: r.lands, d: r.dorks, r: r.rocks, a: r.budget,
  u: SCN.map(s => r1(r.cell[s].useful)), u8: SCN.map(s => r1(r.cell[s].useful8)) }));

// Literal total-budget sweep: only what the page shows (avg spell CMC and useful mana for a few configs)
const B = JSON.parse(fs.readFileSync(budgetFile, 'utf8'));
const show = ['32:5:5', '32:6:6', '36:3:3', '40:2:2', '48:2:2', '54:0:0'];
const budget = B.results.filter(r => r.cell && show.includes(`${r.lands}:${r.dorks}:${r.rocks}`))
  .map(r => ({ l: r.lands, ramp: r.dorks + r.rocks, b: r.budget, cmc: +r.cell.avgSpellCmc.toFixed(2),
    u: r1(SCN.reduce((t, s) => t + r.cell[s].useful, 0) / 8), left: r1(SCN.reduce((t, s) => t + r.cell[s].left, 0) / 8),
    unused: r1(SCN.reduce((t, s) => t + r.cell[s].unused, 0) / 8) }));

const out = { games: A.opts.games, splitGames: S.opts.games, turns: A.opts.turns, avgs, scenarios: A.scenarios,
  configs: configs.map(c => [c.lands, c.ramp]), v, cmd, split, budget };
process.stdout.write('// Generated by tools/sim/manabase/build-lab-data.js from manasim.js results. Values x10 (cmd in %).\n');
process.stdout.write('window.MANA_LAB = ' + JSON.stringify(out) + ';\n');
